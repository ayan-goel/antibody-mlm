"""Measure overlap between the OAS pretraining corpus and every benchmark set.

This is contamination "axis 2" from wiki/10-rebuttal-notes.md §2 — the one axis
the repo never measured, and the one place reviewers can legitimately say we did
not do the work:

    #2.5.2 "Are evaluation proteins clustered away from OAS pretraining
            sequences and from data used to train the paratope and IgFold
            teachers?"

Axes 1, 3 and 4 (OAS train/eval, teacher-train vs probe-test, within-benchmark
split quality) are answered elsewhere. This script answers only axis 2: do the
antibodies we evaluate on also appear in the 497k sequences we pretrained on?

WHY THE OBVIOUS METRIC IS THE WRONG ONE
---------------------------------------
Global percent identity is close to meaningless for antibody VH domains. Every
VH shares the same framework scaffold, so two *unrelated* human antibodies from
the same germline family routinely sit at 80-90% identity. A generic "cluster at
90% identity" audit — the MMseqs2 reflex — would therefore flag most of the
corpus against most of each benchmark and tell us nothing.

What distinguishes one antibody from another is CDR-H3: a 5-30 residue segment
generated by V(D)J recombination plus junctional diversity. Two antibodies
sharing an exact CDR-H3 are, essentially without exception, clonally related.
So this script reports a ladder of increasingly strict criteria:

    exact_vh        the full VH string appears verbatim in the corpus.
                    Unambiguous contamination.
    cdr3_exact      CDR-H3 appears verbatim among the corpus CDR-H3s.
                    Near-certain clonal relationship.
    cdr3_and_v      CDR-H3 match AND same V-gene family. The standard
                    approximate-clonotype definition; strictest evidence.
    max_identity    highest full-VH identity to ANY corpus sequence, found by
                    an 8-mer prefilter plus global alignment. Reported WITH the
                    germline background level below, which is what makes it
                    interpretable.
    background      median max_identity over benchmark antibodies whose CDR-H3
                    does NOT appear in the corpus. This is the "unrelated
                    antibody" floor. max_identity is only evidence of
                    contamination insofar as it exceeds this.

CDR-H3 DEFINITIONS ARE MATCHED ON BOTH SIDES
--------------------------------------------
The corpus carries OAS's own ``cdr3_aa`` annotation. Benchmark sequences are
numbered with ANARCI and CDR-H3 taken as IMGT positions 105-117. These two
definitions were verified identical on 300 randomly sampled corpus sequences
(300/300 exact agreement), so a CDR-H3 comparison across the two sides is
apples-to-apples rather than an artifact of differing conventions.

LIGHT CHAINS
------------
Pretraining is VH-only, so a light chain cannot be contaminated by this corpus.
The structural benchmarks (contact map, structure probe) contain both H and L
chains; ANARCI's chain_type separates them and light chains are reported
separately rather than silently diluting the heavy-chain rate.

Usage:
    PATH=$CONDA_PREFIX/bin:$PATH python scripts/contamination_audit.py
    python scripts/contamination_audit.py --max-identity-sample 4000

ANARCI needs ``hmmscan`` on PATH; it ships in the abmlm env's bin/ directory.
"""

from __future__ import annotations

import argparse
import csv
import json
import logging
import os
import sys
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any, Iterable

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

logger = logging.getLogger(__name__)

AA = "ACDEFGHIKLMNPQRSTVWY"
AA_CODE = {c: i + 1 for i, c in enumerate(AA)}  # 0 reserved for pad/invalid
#: str.translate table -> C-speed encoding; anything non-standard maps to 0 and
#: any k-mer covering it is dropped.
_AA_TABLE = bytes(AA_CODE.get(chr(i), 0) for i in range(256))
KMER_K = 8
KMER_BITS = 5  # 21 symbols fit in 5 bits; k=8 -> 40 bits, fits in uint64

CORPUS_PATH = "data/processed/oas_vh_500k_annotated.jsonl"
OUT_DIR = Path("comparison_outputs")


# ---------------------------------------------------------------------------
# Corpus
# ---------------------------------------------------------------------------

def load_corpus(path: str) -> dict[str, Any]:
    """Load the pretraining corpus with its CDR-H3 and V-gene annotations.

    ``oas_vh_500k_annotated.jsonl`` is verified byte-identical in sequence and
    order to ``oas_vh_500k.jsonl``, the file the configs actually pretrain on,
    so its annotations describe exactly the pretraining set.
    """
    seqs: list[str] = []
    cdr3s: list[str] = []
    vgenes: list[str] = []
    with open(path) as f:
        for line in f:
            d = json.loads(line)
            seqs.append(d["sequence"])
            cdr3s.append(d.get("cdr3_aa") or "")
            vgenes.append((d.get("v_call") or "").split("*")[0])
    logger.info(
        "corpus: %d sequences, %d unique VH, %d unique CDR-H3",
        len(seqs), len(set(seqs)), len({c for c in cdr3s if c}),
    )
    return {"seqs": seqs, "cdr3s": cdr3s, "vgenes": vgenes}


# ---------------------------------------------------------------------------
# 8-mer index for nearest-neighbour prefiltering
# ---------------------------------------------------------------------------

class KmerIndex:
    """Sorted (kmer, sequence_id) index supporting top-N candidate lookup.

    Exists purely to avoid 497k full alignments per query. Two sequences at high
    identity share many exact 8-mers, so ranking corpus sequences by shared
    8-mer count and aligning only the top handful finds the true nearest
    neighbour at a tiny fraction of the cost.
    """

    def __init__(self, sequences: list[str], k: int = KMER_K) -> None:
        self.k = k
        logger.info("building %d-mer index over %d sequences", k, len(sequences))
        keys, ids = [], []
        for i, s in enumerate(sequences):
            codes = np.frombuffer(
                s.encode("ascii", "replace").translate(_AA_TABLE), dtype=np.uint8
            ).astype(np.uint64)
            enc = self._encode(codes, k)
            if enc.size:
                keys.append(enc)
                ids.append(np.full(enc.size, i, dtype=np.uint32))
        key_arr = np.concatenate(keys)
        id_arr = np.concatenate(ids)
        order = np.argsort(key_arr, kind="stable")
        self.keys = key_arr[order]
        self.ids = id_arr[order]
        logger.info("index: %d postings (%.1f MB)", self.keys.size,
                    (self.keys.nbytes + self.ids.nbytes) / 1e6)

    @staticmethod
    def _encode(codes: np.ndarray, k: int) -> np.ndarray:
        """Roll a sequence's amino-acid codes into packed uint64 k-mers."""
        n = codes.size - k + 1
        if n <= 0:
            return np.empty(0, dtype=np.uint64)
        out = np.zeros(n, dtype=np.uint64)
        valid = np.ones(n, dtype=bool)
        for t in range(k):
            window = codes[t : t + n]
            out |= window << np.uint64(KMER_BITS * t)
            valid &= window > 0  # drop k-mers spanning a non-standard residue
        return out[valid]

    def candidates(self, sequence: str, top_n: int) -> np.ndarray:
        """Return corpus ids sharing the most 8-mers with ``sequence``."""
        codes = np.frombuffer(
            sequence.encode("ascii", "replace").translate(_AA_TABLE), dtype=np.uint8
        ).astype(np.uint64)
        query = np.unique(self._encode(codes, self.k))
        if query.size == 0:
            return np.empty(0, dtype=np.int64)
        lo = np.searchsorted(self.keys, query, side="left")
        hi = np.searchsorted(self.keys, query, side="right")
        hits = [self.ids[a:b] for a, b in zip(lo, hi) if b > a]
        if not hits:
            return np.empty(0, dtype=np.int64)
        counts = np.bincount(np.concatenate(hits))
        n = min(top_n, counts.size)
        top = np.argpartition(counts, -n)[-n:]
        return top[np.argsort(counts[top])[::-1]]


# ---------------------------------------------------------------------------
# Identity
# ---------------------------------------------------------------------------

def make_aligner():
    from Bio import Align
    from Bio.Align import substitution_matrices

    aligner = Align.PairwiseAligner(mode="global")
    aligner.substitution_matrix = substitution_matrices.load("BLOSUM62")
    aligner.open_gap_score = -11
    aligner.extend_gap_score = -1
    # Free end gaps: benchmark chains are PDB-derived and often start or end a
    # few residues into the domain, which would otherwise be penalised as
    # internal gaps and understate identity.
    aligner.end_gap_score = 0.0
    return aligner


def percent_identity(aligner, a: str, b: str) -> float:
    """Percent identity over the length of the shorter sequence."""
    try:
        aln = aligner.align(a, b)[0]
    except Exception:  # pragma: no cover - degenerate sequences
        return 0.0
    ta, tb = aln[0], aln[1]
    matches = sum(1 for x, y in zip(ta, tb) if x == y and x != "-")
    return 100.0 * matches / max(1, min(len(a), len(b)))


